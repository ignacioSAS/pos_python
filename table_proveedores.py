#TABLE PROVEEDORES
import psycopg2

try:
    conexion = psycopg2.connect(
        host="localhost",
        database="tienda",
        user="postgres",
        password="postgres",
        port=5432
    )

    cursor = conexion.cursor()
    create_table = """
    CREATE TABLE IF NOT EXISTS proveedores(
        id_proveedor INT GENERATED BY DEFAULT AS IDENTITY(START WITH 5001) NOT NULL,
        nombre_empresa VARCAR(100) NOT NULL,
        email VARCHAR(100) NOT NULL,
        telefono_empresa INTEGER NOT NULL
    );
    """

    cursor.execute(create_table)

    conexion.commit()
    print("Tabla creada")

except Exception as error:
    print(f"Error al crear tabla {error}")

finally:
    if cursor:
        cursor.close()
    if conexion:
        conexion.close()