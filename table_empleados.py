#TABLA EMPLEADOS
import psycopg2

try:
    conexion = psycopg2.connect(
        host="localhost",
        database="tienda",
        user="postgres",
        password="postgres",
        port=5432
    )

    cursor = conexion.cursor()

    create_table = """
    CREATE TABLE IF NOT EXISTS empleados(
        id_empleado INT GENERATED BY DEFAULT AS IDENTITY(START WITH 1001) NOT NULL,
        nombre_empleado VARCHAR(100) NOT NULL,
        telefono_empleado INTEGER NOT NULL,
        fecha_inicio DATE DEFAULT CURRENT_DATE,
        fecha_recesion DATE
    );
    """

    cursor.execute(create_table)

    conexion.commit()
    print("Tabla creada")

except Exception as error:
    print(f"Error al crear tabla {error}")
    
finally:
    if cursor:
        cursor.close()
    if conexion:
        conexion.close()
